import assert from 'node:assert/strict';
import {registerHooks} from 'node:module';
registerHooks({resolve(specifier,context,next){if(specifier==='./course-plan')return next('./course-plan.ts',context);return next(specifier,context);}});
const {reviewWindow,REVIEW_WINDOW_MS}=await import('../lib/review-window.ts');
const {teamProgress,teamAssignmentKind}=await import('../lib/team-progress.ts');
const due='2026-11-09T17:00:00Z',start=Date.parse(due),end=start+7*24*3600000;
assert.equal(REVIEW_WINDOW_MS,end-start);
assert(!reviewWindow({},{due},start-1).open);
assert(reviewWindow({},{due},start).open);
assert(reviewWindow({},{due},end-1).open);
assert(!reviewWindow({},{due},end).open);
assert(reviewWindow({},{due},end).expired);
assert(!reviewWindow({},{}).open);
assert(!reviewWindow({},{due:'nonsense'}).open);
assert.equal(reviewWindow({opensAt:due,expiresAt:new Date(end).toISOString()},{due:'2027-01-01'},start).expiresAt,new Date(end).toISOString());
const members=[{id:'a',name:'A',canvasId:1},{id:'b',name:'B',canvasId:2}],assignment={due,groupCategoryId:5};
const rows=[{owner:'a',workflowState:'submitted',submittedAt:due,syncedAt:due},{owner:'b',workflowState:'unsubmitted',syncedAt:due}];
assert.equal(teamProgress(assignment,members,rows,true).kind,'submitted');
assert.equal(teamProgress(assignment,members,rows,false).kind,'partial');
assert.equal(teamProgress(assignment,members,[],true).kind,'unknown');
assert.notEqual(teamProgress(assignment,members,[{owner:'a',workflowState:'graded',submittedAt:null,submissionType:null}],true).kind,'submitted','A zero grade without submission evidence is not a submission');
assert.equal(teamProgress(assignment,[],[],true).kind,'unknown');
assert.equal(teamProgress(assignment,members,[rows[1]],true).kind,'unknown');
const missing=members.map(p=>({owner:p.id,workflowState:'unsubmitted',syncedAt:due}));
assert.equal(teamProgress(assignment,members,missing,true,start-3600000).reminder,'Due within 24 hours');
assert.equal(teamProgress(assignment,members,missing,true,start+1).kind,'not-submitted');
assert.equal(teamProgress(assignment,members,rows,true).reminder,null);
assert(teamProgress(assignment,members,[{...rows[0],due},{...rows[1],due:'2026-11-20T17:00:00Z'}],true).individualDeadlines);
assert.equal(teamAssignmentKind({title:'Work-In-Progress Brand Placemaking Presentation'}),'Work in Progress');
assert.equal(teamAssignmentKind({title:'Final Brand Placemaking Presentation & Recommendation'}),'Final Presentation');
assert.equal(teamAssignmentKind({title:'Choose your Brand Project'}),null);
console.log('PASS exact 7-day boundaries, pre-open/expired/missing-date lock, frozen invitation deadline; group shared-vs-individual coverage, unknown vs missing, extension and reminder cases.');
